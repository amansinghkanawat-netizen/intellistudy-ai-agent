import React, { useState, useEffect } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import {
  ChevronLeft, ChevronRight, RotateCcw, Check, Sparkles,
  Plus, Loader, BookOpen, Star, AlertTriangle, Eye, EyeOff
} from 'lucide-react'
import { flashcardAPI, resourceAPI } from '../services/api'
import { PageHeader, DemoModeBanner, ProgressBar, EmptyState, PageLoader } from '../components/ui/index.jsx'
import toast from 'react-hot-toast'

const DIFFICULTY_STYLES = {
  easy:   { text: 'text-emerald-400', bg: 'bg-emerald-500/20', border: 'border-emerald-500/30' },
  medium: { text: 'text-amber-400',   bg: 'bg-amber-500/20',   border: 'border-amber-500/30' },
  hard:   { text: 'text-red-400',     bg: 'bg-red-500/20',     border: 'border-red-500/30' },
}

export default function FlashcardsPage() {
  const [sets, setSets] = useState([])
  const [activeSet, setActiveSet] = useState(null)
  const [cards, setCards] = useState([])
  const [currentIdx, setCurrentIdx] = useState(0)
  const [flipped, setFlipped] = useState(false)
  const [mastered, setMastered] = useState(new Set())
  const [mode, setMode] = useState('all')
  const [loading, setLoading] = useState(true)
  const [generating, setGenerating] = useState(false)
  const [resources, setResources] = useState([])
  const [showHint, setShowHint] = useState(false)

  useEffect(() => {
    loadSets()
    resourceAPI.list()
      .then((data) => setResources(data.filter((r) => r.status === 'completed')))
      .catch(() => {})
  }, [])

  const loadSets = async () => {
    setLoading(true)
    try {
      const data = await flashcardAPI.list()
      setSets(data)
      if (data.length > 0 && !activeSet) {
        loadSet(data[0])
      }
    } catch {
      // silent
    } finally {
      setLoading(false)
    }
  }

  const loadSet = async (set) => {
    setActiveSet(set)
    try {
      const full = await flashcardAPI.getSet(set.id)
      setCards(full.cards || [])
      setMastered(new Set((full.cards || []).filter((c) => c.mastered).map((c) => c.id)))
      setCurrentIdx(0)
      setFlipped(false)
      setMode('all')
    } catch {
      // silent
    }
  }

  const generateNew = async (resourceId = null) => {
    setGenerating(true)
    try {
      const data = await flashcardAPI.generate({ resource_id: resourceId || undefined, count: 10 })
      toast.success(data.demo_mode ? 'Flashcards generated (Demo mode)' : 'Flashcards generated by IBM Granite!')
      // Load the new set
      setCards(data.cards || [])
      setActiveSet({ id: data.set_id, title: data.title, is_demo: data.demo_mode })
      setMastered(new Set())
      setCurrentIdx(0)
      setFlipped(false)
      setMode('all')
      await loadSets()
    } catch {
      // handled globally
    } finally {
      setGenerating(false)
    }
  }

  const toggleMastered = async (card) => {
    const wasM = mastered.has(card.id)
    setMastered((prev) => {
      const n = new Set(prev)
      wasM ? n.delete(card.id) : n.add(card.id)
      return n
    })
    try {
      await flashcardAPI.update(card.id, { mastered: !wasM })
    } catch {
      // revert
      setMastered((prev) => {
        const n = new Set(prev)
        wasM ? n.add(card.id) : n.delete(card.id)
        return n
      })
    }
  }

  const filtered = mode === 'all' ? cards : cards.filter((c) => !mastered.has(c.id))
  const card = filtered[currentIdx] ?? null
  const total = filtered.length
  const masteredCount = mastered.size

  const goTo = (idx) => {
    setCurrentIdx(Math.max(0, Math.min(idx, total - 1)))
    setFlipped(false)
    setShowHint(false)
  }

  if (loading) return <PageLoader text="Loading flashcards..." />

  return (
    <div className="max-w-5xl mx-auto space-y-6">
      <PageHeader
        title="Smart Flashcards"
        description="Click any card to flip it. Use keyboard: Space to flip · Arrow keys to navigate."
        action={
          <div className="flex gap-2">
            {resources.length > 0 && (
              <div className="relative group">
                <button
                  disabled={generating}
                  className="btn-secondary text-sm py-2.5 px-4 flex items-center gap-2"
                  onClick={() => generateNew()}
                >
                  {generating ? <Loader className="w-4 h-4 animate-spin" /> : <Plus className="w-4 h-4" />}
                  {generating ? 'Generating...' : 'Generate'}
                </button>
              </div>
            )}
            {resources.length === 0 && (
              <button
                onClick={() => generateNew()}
                disabled={generating}
                className="btn-primary text-sm py-2.5 flex items-center gap-2"
              >
                {generating ? <Loader className="w-4 h-4 animate-spin" /> : <Sparkles className="w-4 h-4" />}
                {generating ? 'Generating...' : 'Generate Demo Cards'}
              </button>
            )}
          </div>
        }
      />

      {/* Generate from resource */}
      {resources.length > 0 && (
        <div className="card p-4">
          <p className="text-gray-400 text-xs mb-3 font-medium">Generate flashcards from your study material:</p>
          <div className="flex flex-wrap gap-2">
            <button
              onClick={() => generateNew(null)}
              disabled={generating}
              className="text-xs px-3 py-1.5 rounded-lg bg-indigo-500/15 border border-indigo-500/30 text-indigo-400 hover:bg-indigo-500/25 transition-all disabled:opacity-50"
            >
              {generating ? <Loader className="w-3 h-3 inline animate-spin mr-1" /> : null}
              Demo Cards
            </button>
            {resources.map((r) => (
              <button
                key={r.id}
                onClick={() => generateNew(r.id)}
                disabled={generating}
                className="text-xs px-3 py-1.5 rounded-lg border border-gray-700 text-gray-400 hover:border-indigo-500/40 hover:text-indigo-400 hover:bg-indigo-500/10 transition-all truncate max-w-40 disabled:opacity-50"
              >
                📄 {r.original_name}
              </button>
            ))}
          </div>
        </div>
      )}

      {sets.length === 0 && cards.length === 0 ? (
        <div className="card">
          <EmptyState
            icon={BookOpen}
            title="No flashcard collections yet"
            description="Generate flashcards from your study materials or start with demo cards."
            action={
              <button onClick={() => generateNew()} disabled={generating} className="btn-primary text-sm py-2.5 px-5 flex items-center gap-2">
                {generating ? <Loader className="w-4 h-4 animate-spin" /> : <Sparkles className="w-4 h-4" />}
                Generate Demo Flashcards
              </button>
            }
          />
        </div>
      ) : (
        <div className="grid lg:grid-cols-3 gap-6">
          {/* Collections panel */}
          {sets.length > 0 && (
            <div className="card p-4 space-y-2 h-fit">
              <h3 className="text-white font-semibold text-sm mb-3">Your Collections</h3>
              {sets.map((s) => (
                <button
                 key={s.id}
                 onClick={() => loadSet(s)}
                  className={`w-full text-left p-3 rounded-xl border transition-all text-sm ${
                    activeSet?.id === s.id
                      ? 'bg-indigo-500/15 border-indigo-500/30 text-white'
                      : 'border-gray-800 text-gray-400 hover:border-gray-700 hover:text-gray-200'
                  }`}
                >
                  <p className="font-medium truncate">{s.title}</p>
                  <p className="text-xs text-gray-500 mt-0.5">{s.card_count} cards{s.is_demo ? ' · Demo' : ''}</p>
                </button>
              ))}
            </div>
          )}

          {/* Flashcard viewer */}
          {cards.length > 0 && (
            <div className={`space-y-5 ${sets.length > 0 ? 'lg:col-span-2' : 'col-span-3'}`}>
              {activeSet?.is_demo && (
                <DemoModeBanner message="Demo flashcards — real cards are generated from your uploaded study materials." />
              )}

              {/* Controls */}
              <div className="flex items-center justify-between">
                <div className="flex gap-2">
                  <button
                    onClick={() => { setMode('all'); setCurrentIdx(0); setFlipped(false) }}
                    className={`text-xs px-3 py-1.5 rounded-lg border transition-all ${mode === 'all' ? 'bg-indigo-500/20 border-indigo-500/40 text-indigo-400' : 'border-gray-700 text-gray-400 hover:border-gray-600'}`}
                  >
                    All ({cards.length})
                  </button>
                  <button
                    onClick={() => { setMode('unmastered'); setCurrentIdx(0); setFlipped(false) }}
                    className={`text-xs px-3 py-1.5 rounded-lg border transition-all ${mode === 'unmastered' ? 'bg-indigo-500/20 border-indigo-500/40 text-indigo-400' : 'border-gray-700 text-gray-400 hover:border-gray-600'}`}
                  >
                    Review ({cards.length - masteredCount})
                  </button>
                </div>
                <div className="flex items-center gap-2 text-xs text-gray-400">
                  <Star className="w-3.5 h-3.5 text-yellow-400" fill="currentColor" />
                  {masteredCount}/{cards.length} mastered
                </div>
              </div>

              {/* Progress bar */}
              <div className="space-y-1">
                <div className="flex justify-between text-xs text-gray-500">
                  <span>{currentIdx + 1} of {total}</span>
                  <span>{Math.round((masteredCount / cards.length) * 100)}% mastered</span>
                </div>
                <ProgressBar value={masteredCount} max={cards.length} color="bg-yellow-500" />
              </div>

              {/* Card */}
              {card ? (
                <div
                  className="relative cursor-pointer select-none"
                  onClick={() => { setFlipped(!flipped); setShowHint(false) }}
                  style={{ perspective: '1200px', minHeight: 300 }}
                >
                  <motion.div
                    animate={{ rotateY: flipped ? 180 : 0 }}
                    transition={{ duration: 0.5, ease: [0.4, 0, 0.2, 1] }}
                    style={{ transformStyle: 'preserve-3d' }}
                    className="relative w-full"
                  >
                    {/* Front */}
                    <div
                      className="card p-8 md:p-10 text-center min-h-72 flex flex-col items-center justify-center"
                      style={{ backfaceVisibility: 'hidden' }}
                    >
                      <div className="flex items-center gap-2 mb-6">
                        <span className={`badge border ${DIFFICULTY_STYLES[card.difficulty]?.text || ''} ${DIFFICULTY_STYLES[card.difficulty]?.bg || ''} ${DIFFICULTY_STYLES[card.difficulty]?.border || ''}`}>
                          {card.difficulty}
                        </span>
                        <span className="text-gray-500 text-xs">Question</span>
                        {mastered.has(card.id) && (
                          <span className="badge bg-yellow-500/20 text-yellow-400 border border-yellow-500/30 ml-1">
                            <Star className="w-3 h-3 mr-0.5" fill="currentColor" />Mastered
                          </span>
                        )}
                      </div>
                      <p className="text-white text-xl font-semibold leading-relaxed mb-6">{card.front}</p>
                      <div className="flex items-center gap-2">
                        <button
                          onClick={(e) => { e.stopPropagation(); setShowHint(!showHint) }}
                          className="text-xs text-gray-500 hover:text-indigo-400 transition-colors flex items-center gap-1"
                        >
                          {showHint ? <EyeOff className="w-3 h-3" /> : <Eye className="w-3 h-3" />}
                          {showHint ? 'Hide' : 'Peek'}
                        </button>
                      </div>
                      {showHint && (
                        <motion.p
                          initial={{ opacity: 0, blur: '8px' }}
                          animate={{ opacity: 1 }}
                          className="text-indigo-300/70 text-sm mt-3 italic blur-sm hover:blur-none transition-all cursor-pointer"
                          onClick={(e) => { e.stopPropagation(); setFlipped(true) }}
                        >
                          {card.back.slice(0, 60)}...
                        </motion.p>
                      )}
                      <p className="text-gray-500 text-xs mt-4">Click to flip · Space key</p>
                    </div>

                    {/* Back */}
                    <div
                      className="card p-8 md:p-10 text-center min-h-72 flex flex-col items-center justify-center absolute inset-0 bg-gradient-to-br from-indigo-900/40 to-violet-900/20"
                      style={{ backfaceVisibility: 'hidden', transform: 'rotateY(180deg)' }}
                    >
                      <span className="badge bg-indigo-500/20 text-indigo-400 border border-indigo-500/30 mb-6">Answer</span>
                      <p className="text-gray-200 text-base leading-relaxed">{card.back}</p>
                    </div>
                  </motion.div>
                </div>
              ) : (
                <div className="card p-16 text-center">
                  <Star className="w-12 h-12 text-yellow-400 mx-auto mb-4" fill="currentColor" />
                  <p className="text-white font-semibold text-lg">All cards mastered! 🎉</p>
                  <p className="text-gray-400 text-sm mt-1">Switch to "All" to review again.</p>
                </div>
              )}

              {/* Controls */}
              <div className="flex items-center justify-between">
                <button
                  onClick={() => goTo(currentIdx - 1)}
                  disabled={currentIdx === 0}
                  className="btn-secondary text-sm py-2.5 px-5 flex items-center gap-2 disabled:opacity-40"
                >
                  <ChevronLeft className="w-4 h-4" /> Previous
                </button>

                <div className="flex gap-2">
                  <button
                    onClick={() => { setCurrentIdx(0); setFlipped(false) }}
                    className="p-2.5 rounded-xl bg-gray-800 text-gray-400 hover:text-white hover:bg-gray-700 transition-all"
                    title="Restart"
                  >
                    <RotateCcw className="w-4 h-4" />
                  </button>
                  {card && (
                    <button
                      onClick={(e) => { e.stopPropagation(); toggleMastered(card) }}
                      className={`p-2.5 rounded-xl border transition-all ${
                        mastered.has(card?.id)
                          ? 'bg-yellow-500/20 border-yellow-500/40 text-yellow-400'
                          : 'bg-gray-800 border-gray-700 text-gray-400 hover:text-yellow-400 hover:border-yellow-500/40'
                      }`}
                      title={mastered.has(card?.id) ? 'Unmark mastered' : 'Mark as mastered'}
                    >
                      <Star className="w-4 h-4" fill={mastered.has(card?.id) ? 'currentColor' : 'none'} />
                    </button>
                  )}
                </div>

                <button
                  onClick={() => goTo(currentIdx + 1)}
                  disabled={currentIdx >= total - 1}
                  className="btn-secondary text-sm py-2.5 px-5 flex items-center gap-2 disabled:opacity-40"
                >
                  Next <ChevronRight className="w-4 h-4" />
                </button>
              </div>

              {/* Card grid */}
              <div className="flex gap-1.5 flex-wrap">
                {cards.map((c, i) => {
                  const inFiltered = filtered.indexOf(c)
                  const isCurrent = inFiltered === currentIdx
                  return (
                    <button
                      key={c.id}
                      onClick={() => {
                        const idx = filtered.indexOf(c)
                        if (idx !== -1) goTo(idx)
                      }}
                      className={`w-9 h-9 rounded-lg text-xs font-semibold border transition-all ${
                        isCurrent ? 'bg-indigo-500/30 border-indigo-500/60 text-indigo-400' :
                        mastered.has(c.id) ? 'bg-yellow-500/15 border-yellow-500/30 text-yellow-400' :
                        'bg-gray-800 border-gray-700 text-gray-500 hover:border-gray-600'
                      }`}
                    >
                      {i + 1}
                    </button>
                  )
                })}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  )
}
